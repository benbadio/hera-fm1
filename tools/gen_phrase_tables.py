"""Generate firmware/src/j6/j6_phrase_tables.h: the event lists of phrase styles 6..9 (PH-17 .. PH-19).

    python3 -I tools/gen_phrase_tables.py                  DERIVED lists from data/phrases_6_9.json when
                                                           that file exists, else PLACEHOLDER lists
    python3 -I tools/gen_phrase_tables.py --derived FILE   DERIVED lists from another phrase table file
    python3 -I tools/gen_phrase_tables.py --placeholder    PLACEHOLDER lists for all 192 slots
    python3 -I tools/gen_phrase_tables.py --check          regenerate in the mode (and from the source) the
                                                           committed header records, compare, exit 1 if it
                                                           differs or the source changed
    (--output FILE writes / checks another file)

Standard library only. Nothing is ever written under capture/ or data/.

The header holds j6p_-prefixed static const data only, in the j6.h section 6 format: j6p_pool[J6P_POOL_LEN]
(j6_pev_t) and j6p_lists[J6_PLISTS] (j6_plist_t, indexed by j6_plist_index(style, var, n)). Its first line
records the mode, the source file and the source's SHA-256, so --check can tell a stale header.

DERIVED lists (flags J6_PL_CAPTURED) are the real J-6 phrases. data/phrases_6_9.json was derived from the J-6
capture (capture/raw/phrases.jsonl, keys s{style}v{var:02d}n{n}) by tools/derive_phrases.py: latency-aligned,
every loop confirmed by repetition, every onset on a 4-tick grid. Its format:
    {"PPQN": 96, "held": {"1": [60], ..., "4": [60, 64, 67, 71]},
     "phrases": {"s6v01": {"1": {"loop": L, "repeats": true, "bpm": B,
                                 "notes": [{"t": T, "len": D, "tone": I, "oct": O, "acc": A}, ...]},
                           "2": {...}, "3": {...}, "4": {...}}, ..., "s9v12": {...}}}
Every value is in ticks at 96 PPQN from the loop start, and the conversion is 1:1:
    j6_pev_t.t    = T * 16              (sub-ticks; strums are whole ticks, multiples of 4, tempo-relative)
    j6_pev_t.len  = D * 16              (the gate the J-6 played, not j6_gate() of anything)
    j6_pev_t.src  = I | (A ? J6_PEV_ACCENT : 0)   (I indexes the SORTED held set; accent = A.vLo)
    j6_pev_t.semi = O * 12              (always 0 in the J-6 data: styles 6-9 play only the held tones)
    j6_plist_t.loop = L                 (2, 3, 4, 6 or 8 beats)
Events are sorted by (t, tone). A list missing from the file falls back to its placeholder (named in the
header); a malformed list is an error.

PLACEHOLDER lists (flags 0) are NOT J-6 behaviour. They are the PH-19 fallback when no derived file is
there, with a 384-tick loop and gates g(len) (j6_gate):
  style 6 v: the hits of style 4 v, 4 times per bar, all of H; the first hit of the bar also plays H[0]-12
  style 7 v: the hits of style 5 v (v7-12: the 72-tick string restarted every bar), all of H, accent on
             the first hit of each beat
  style 8 v: style 6 v strummed upward: note i of H is 2*i ticks late
  style 9 v: style 7 v strummed: even hits (0-based, in the bar) up, odd hits down
"""
import hashlib
import json
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
DEFAULT_OUTPUT = os.path.join(ROOT, "firmware", "src", "j6", "j6_phrase_tables.h")
DEFAULT_DERIVED = "data/phrases_6_9.json"     # relative to ROOT; recorded like this in the header

STYLES = (6, 7, 8, 9)
VARS = 12
NMAX = 4
PLISTS = len(STYLES) * VARS * NMAX            # J6_PLISTS
SUB = 16                                      # J6_SUB
PPQN = 96
BAR = 384
BEAT = 96
SIXTEENTH = 24
PL_CAPTURED = 0x01                            # J6_PL_CAPTURED
PEV_ACCENT = 0x80                             # J6_PEV_ACCENT
LOOP_MAX = 4095                               # j6_plist_t.loop
U16_MAX = 65535
TICK_EVENTS_MAX = 16                          # j6_phrase.c starts at most this many notes in one tick
ACTIVE_MAX = 16                               # j6_phrase.c: J6P_ACTIVE_MAX notes sounding at once
DERIVED_HELD = {1: [60], 2: [60, 67], 3: [60, 64, 67], 4: [60, 64, 67, 71]}

# PH-15 rhythm strings (the manual's phrase list), the same as in j6_phrase.c
STYLE4 = ("o___", "_o__", "__o_", "___o", "o~o_", "o_o~", "o~~o", "_o~o", "ooo_", "oo_o", "o_oo", "_ooo")
STYLE5 = ("oo__", "o_o_", "o__o", "_oo_", "_o_o", "__oo", "o__", "_o_", "__o", "oo_", "o_o", "_oo")

HEADER_RE = re.compile(r"^/\* generated by tools/gen_phrase_tables\.py mode=(placeholder|derived) "
                       r"source=(\S+) sha256=([0-9a-f]{64}|none) - do not edit \*/$")


class DataError(Exception):
    pass


def gate(length):
    """PH-7 / j6_gate(): L - min(L/5, 10) ticks"""
    return length - min(length // 5, 10)


def key_of(style, var):
    return "s%dv%02d" % (style, var)


def rhythm_hits(s):
    """'o~o_' -> [(onset ticks, length ticks)]"""
    hits = []
    for i, c in enumerate(s):
        if c == "o":
            hits.append([i * SIXTEENTH, SIXTEENTH])
        elif c == "~":
            if not hits:
                raise DataError("rhythm string %r starts with ~" % s)
            hits[-1][1] += SIXTEENTH
        elif c != "_":
            raise DataError("rhythm string %r: bad character %r" % (s, c))
    return [tuple(h) for h in hits]


# ---------------------------------------------------------------------------------------------------
# PH-19 placeholders


def bar_hits(style, var):
    """the hits of one 384-tick bar of the placeholder of a style 6..9 variation: [(onset, length)]"""
    if style in (6, 8):
        base = rhythm_hits(STYLE4[var - 1])
        return [(r * BEAT + o, ln) for r in range(4) for o, ln in base]
    s = STYLE5[var - 1]
    loop = len(s) * SIXTEENTH
    base = rhythm_hits(s)
    out = []
    for k in range(0, BAR // loop + 1):
        for o, ln in base:
            if k * loop + o < BAR:
                out.append((k * loop + o, ln))
    return sorted(out)


def placeholder(style, var, n):
    """(loop ticks, [(t sub, len sub, src, semi)], flags) for the PH-19 placeholder of a list"""
    hits = bar_hits(style, var)
    events = []
    seen_beats = set()
    for hi, (onset, length) in enumerate(hits):
        g = gate(length) * SUB
        accent = 0
        if style in (7, 9):
            beat = onset // BEAT
            if beat not in seen_beats:
                seen_beats.add(beat)
                accent = PEV_ACCENT
        for i in range(n):
            if style == 8 or (style == 9 and hi % 2 == 0):
                delay = 2 * i
            elif style == 9:
                delay = 2 * (n - 1 - i)
            else:
                delay = 0
            events.append(((onset + delay) * SUB, g, i | accent, 0))
        if style in (6, 8) and hi == 0:
            events.append((onset * SUB, g, 0, -12))
    events.sort(key=lambda e: (e[0], e[2] & 3, e[3]))
    return BAR, events, 0


# ---------------------------------------------------------------------------------------------------
# derived J-6 phrases (data/phrases_6_9.json)


def as_int(v, where, lo, hi):
    if isinstance(v, bool) or not isinstance(v, (int, float)) or int(v) != v:
        raise DataError("%s: %r is not a whole number" % (where, v))
    v = int(v)
    if not lo <= v <= hi:
        raise DataError("%s: %d not in %d..%d" % (where, v, lo, hi))
    return v


def derived_list(where, rec, n):
    """(loop ticks, [(t sub, len sub, src, semi)], flags) of one list of the derived file"""
    if not isinstance(rec, dict):
        raise DataError("%s: not an object" % where)
    loop = as_int(rec.get("loop"), where + " loop", 1, LOOP_MAX)
    notes = rec.get("notes")
    if not isinstance(notes, list) or not notes:
        raise DataError("%s: no notes" % where)
    events = []
    for i, e in enumerate(notes):
        w = "%s note %d" % (where, i)
        if not isinstance(e, dict):
            raise DataError(w + ": not an object")
        t = as_int(e.get("t"), w + " t", 0, loop - 1)
        ln = as_int(e.get("len"), w + " len", 1, U16_MAX // SUB)
        tone = as_int(e.get("tone"), w + " tone", 0, n - 1)
        octv = as_int(e.get("oct", 0), w + " oct", -2, 2)
        acc = as_int(e.get("acc", 0), w + " acc", 0, 1)
        events.append((t * SUB, ln * SUB, tone | (PEV_ACCENT if acc else 0), 12 * octv))
    events.sort(key=lambda e: (e[0], e[2] & 3, e[3]))
    return loop, events, PL_CAPTURED


def read_derived(raw, path):
    """{(style, var, n): list} from the bytes of a derived file"""
    try:
        doc = json.loads(raw.decode("utf-8"))
    except ValueError as ex:
        raise DataError("%s is not JSON: %s" % (path, ex))
    if not isinstance(doc, dict) or not isinstance(doc.get("phrases"), dict):
        raise DataError("%s: no \"phrases\" object" % path)
    if doc.get("PPQN", PPQN) != PPQN:
        raise DataError("%s: PPQN %r, the engine runs at %d" % (path, doc.get("PPQN"), PPQN))
    held = doc.get("held")
    if held is not None:
        for n, notes in DERIVED_HELD.items():
            if held.get(str(n)) != notes:
                raise DataError("%s: held[%d] is %r, expected %r" % (path, n, held.get(str(n)), notes))
    out = {}
    for style in STYLES:
        for var in range(1, VARS + 1):
            pv = doc["phrases"].get(key_of(style, var))
            if pv is None:
                continue
            if not isinstance(pv, dict):
                raise DataError("%s %s: not an object" % (path, key_of(style, var)))
            for n in range(1, NMAX + 1):
                rec = pv.get(str(n))
                if rec is not None:
                    out[(style, var, n)] = derived_list("%s n%d" % (key_of(style, var), n), rec, n)
    return out


# ---------------------------------------------------------------------------------------------------
# the header


def check_list(name, loop, events):
    """the engine's limits (j6.h section 6, j6_phrase.c)"""
    if not 1 <= loop <= LOOP_MAX:
        raise DataError("%s: loop %d out of range" % (name, loop))
    if not events:
        raise DataError("%s: no events" % name)
    if len(events) > U16_MAX:
        raise DataError("%s: too many events" % name)
    per_tick = {}
    for t, ln, src, semi in events:
        if not 0 <= t < loop * SUB:
            raise DataError("%s: onset %d sub-ticks outside the %d-tick loop" % (name, t, loop))
        if not 1 <= ln <= U16_MAX:
            raise DataError("%s: gate %d sub-ticks out of range" % (name, ln))
        if src & ~(0x03 | PEV_ACCENT):
            raise DataError("%s: src 0x%02x uses reserved bits" % (name, src))
        if not -128 <= semi <= 127:
            raise DataError("%s: semi %d out of range" % (name, semi))
        per_tick[t // SUB] = per_tick.get(t // SUB, 0) + 1
    if max(per_tick.values()) > TICK_EVENTS_MAX:
        raise DataError("%s: more than %d events in one tick" % (name, TICK_EVENTS_MAX))
    # notes sounding at once over two loops (the engine keeps J6P_ACTIVE_MAX)
    marks = []
    for k in (0, 1):
        for t, ln, src, semi in events:
            marks.append((k * loop * SUB + t, 1))
            marks.append((k * loop * SUB + t + ln, -1))
    marks.sort()
    depth = peak = 0
    for _, d in marks:
        depth += d
        peak = max(peak, depth)
    if peak > ACTIVE_MAX:
        raise DataError("%s: %d notes at once, the engine keeps %d" % (name, peak, ACTIVE_MAX))


def build(mode, derived):
    """[(style, var, n, loop, events, flags, origin)] in j6_plist_index order"""
    lists = []
    for style in STYLES:
        for var in range(1, VARS + 1):
            for n in range(1, NMAX + 1):
                if mode == "derived" and (style, var, n) in derived:
                    loop, events, flags = derived[(style, var, n)]
                    origin = "J-6"
                else:
                    loop, events, flags = placeholder(style, var, n)
                    origin = "PLACEHOLDER"
                check_list("%s n%d" % (key_of(style, var), n), loop, events)
                lists.append((style, var, n, loop, events, flags, origin))
    return lists


def render(mode, source, digest, lists):
    pool_len = sum(len(x[4]) for x in lists)
    if pool_len > U16_MAX:
        raise DataError("pool of %d events does not fit j6_plist_t.first" % pool_len)
    n_der = sum(1 for x in lists if x[6] == "J-6")
    n_acc = sum(1 for x in lists for e in x[4] if e[2] & PEV_ACCENT)
    loops = {}
    for x in lists:
        loops[x[3]] = loops.get(x[3], 0) + 1
    most = max(len(x[4]) for x in lists)
    out = []
    w = out.append
    w("/* generated by tools/gen_phrase_tables.py mode=%s source=%s sha256=%s - do not edit */"
      % (mode, source, digest))
    w("/* SPDX-License-Identifier: GPL-3.0-only */")
    w("/* j6_phrase_tables.h - the event lists of phrase styles 6..9 (PH-17 .. PH-19), included by")
    w(" * j6_phrase.c only (j6_phrase_builtin). Format: j6.h section 6; list index j6_plist_index(style, var, n).")
    w(" *")
    if mode == "derived":
        w(" * DERIVED: the real J-6 phrases from %s (tools/derive_phrases.py over the J-6" % source)
        w(" * capture, held notes [60] [60 67] [60 64 67] [60 64 67 71]): %d of %d lists carry J6_PL_CAPTURED."
          % (n_der, len(lists)))
        w(" * t / len are the captured ticks * 16; src = tone index into the sorted H | J6_PEV_ACCENT (A.vLo);")
        w(" * semi = oct * 12 (0 throughout: the J-6 plays only the held tones). Strum offsets are whole ticks")
        w(" * (multiples of 4) and scale with the tempo.")
        if n_der < len(lists):
            w(" * Lists missing from the source play the PH-19 PLACEHOLDER (flags 0):")
            miss = ["%s n%d" % (key_of(x[0], x[1]), x[2]) for x in lists if x[6] != "J-6"]
            for i in range(0, len(miss), 8):
                w(" *   " + ", ".join(miss[i:i + 8]))
    else:
        w(" * PLACEHOLDER: every list is the PH-19 placeholder (flags 0), NOT J-6 behaviour: style 6 = style 4")
        w(" * hits x4 per bar plus H[0]-12 on the first; 7 = style 5 hits, accent on each beat's first; 8 = 6")
        w(" * strummed up (2 ticks per note); 9 = 7 strummed up / down. Loop 384, gates g(len).")
    w(" * %d events (%d accented), at most %d per list; loops (ticks: lists) %s."
      % (pool_len, n_acc, most, ", ".join("%d: %d" % (k, loops[k]) for k in sorted(loops))))
    w(" * Regenerate with: python3 -I tools/gen_phrase_tables.py */")
    w("#ifndef J6P_PHRASE_TABLES_H")
    w("#define J6P_PHRASE_TABLES_H")
    w("")
    w('#include "j6.h"')
    w("")
    w("#define J6P_POOL_LEN %du" % pool_len)
    w("")
    w("/* {t sub-ticks, len sub-ticks, src (tone | 0x80 accent), semi} */")
    w("static const j6_pev_t j6p_pool[J6P_POOL_LEN] = {")
    firsts = []
    first = 0
    for style, var, n, loop, events, flags, origin in lists:
        firsts.append(first)
        w("    /* %s n%d: loop %d, %d events, %s */" % (key_of(style, var), n, loop, len(events), origin))
        line = "   "
        for t, ln, src, semi in events:
            item = " {%d, %d, 0x%02x, %d}," % (t, ln, src, semi)
            if len(line) + len(item) > 116:
                w(line)
                line = "   "
            line += item
        if line.strip():
            w(line)
        first += len(events)
    w("};")
    w("")
    w("/* {loop ticks, first, count, flags, reserved}, j6_plist_index order: style 6..9, var 1..12, n 1..4 */")
    w("static const j6_plist_t j6p_lists[J6_PLISTS] = {")
    for i, (style, var, n, loop, events, flags, origin) in enumerate(lists):
        w("    {%d, %d, %d, 0x%02x, 0}, /* %d: %s n%d */" % (loop, firsts[i], len(events), flags, i,
                                                       key_of(style, var), n))
    w("};")
    w("")
    w("#endif /* J6P_PHRASE_TABLES_H */")
    return "\n".join(out) + "\n"


def generate(mode, source):
    """(header text) for a mode; source is the derived file path as recorded (relative to ROOT)"""
    if mode == "derived":
        path = source if os.path.isabs(source) else os.path.join(ROOT, source)
        with open(path, "rb") as f:
            raw = f.read()
        digest = hashlib.sha256(raw).hexdigest()
        return render(mode, source, digest, build(mode, read_derived(raw, source)))
    return render("placeholder", "none", "none", build("placeholder", {}))


def rel(path):
    a = os.path.abspath(path)
    if a.startswith(ROOT + os.sep):
        return os.path.relpath(a, ROOT).replace(os.sep, "/")
    return a


def main(argv):
    mode = None
    source = None
    check = False
    output = DEFAULT_OUTPUT
    k = 1
    while k < len(argv):
        a = argv[k]
        if a == "--check":
            check = True
        elif a == "--placeholder":
            mode = "placeholder"
        elif a == "--derived":
            mode = "derived"
            if k + 1 < len(argv) and not argv[k + 1].startswith("--"):
                source = rel(argv[k + 1])
                k += 1
        elif a == "--output" and k + 1 < len(argv):
            output = argv[k + 1]
            k += 1
        else:
            sys.stderr.write(__doc__)
            return 2
        k += 1

    if check:
        try:
            with open(output, encoding="utf-8") as f:
                first = f.readline().rstrip("\n")
                committed = first + "\n" + f.read()
        except OSError as ex:
            print("gen_phrase_tables: cannot read %s: %s" % (output, ex))
            return 1
        m = HEADER_RE.match(first)
        if not m:
            print("gen_phrase_tables: %s has no generator header line" % output)
            return 1
        mode, source, digest = m.group(1), m.group(2), m.group(3)
        if mode == "derived":
            path = source if os.path.isabs(source) else os.path.join(ROOT, source)
            try:
                with open(path, "rb") as f:
                    now = hashlib.sha256(f.read()).hexdigest()
            except OSError:
                print("gen_phrase_tables: %s was generated from %s, which is missing" % (output, source))
                return 1
            if now != digest:
                print("gen_phrase_tables: %s changed since %s was generated: run tools/gen_phrase_tables.py"
                      % (source, output))
                return 1
        try:
            text = generate(mode, source)
        except (DataError, OSError) as ex:
            print("gen_phrase_tables: %s" % ex)
            return 1
        if text != committed:
            print("gen_phrase_tables: %s is out of date (mode %s): run tools/gen_phrase_tables.py" % (output, mode))
            return 1
        print("gen_phrase_tables: %s up to date (mode %s)" % (rel(output), mode))
        return 0

    if mode is None:
        mode = "derived" if os.path.exists(os.path.join(ROOT, DEFAULT_DERIVED)) else "placeholder"
    if mode == "derived" and source is None:
        source = DEFAULT_DERIVED
    try:
        text = generate(mode, source)
    except (DataError, OSError) as ex:
        print("gen_phrase_tables: %s" % ex)
        return 1
    with open(output, "w", encoding="utf-8") as f:
        f.write(text)
    print("gen_phrase_tables: wrote %s (mode %s%s)" % (rel(output), mode,
                                                     ", source " + source if mode == "derived" else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
