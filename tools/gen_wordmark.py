"""Render the HERA wordmark (Playfair Display Black, SIL OFL 1.1) to firmware/gen/hera_wordmark.h.

The splash screen draws it from this bitmap (4-bit coverage, two pixels a byte), so the FM-1 needs no font
renderer. Run it when the look changes; the generated header is committed:

    python3 tools/gen_wordmark.py /path/to/PlayfairDisplay[wght].ttf
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

WORD = "HERA"
WIDTH = 220                 # pixels on the 240-pixel screen
BIG = 480                   # the size it is drawn at before it is scaled down
OVERLAP = 0.012             # tracking: the letters nearly touch


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    font = ImageFont.truetype(sys.argv[1], BIG)
    font.set_variation_by_axes([900])
    pad = BIG // 4
    canvas = Image.new("L", (BIG * 4, BIG * 2), 0)
    d = ImageDraw.Draw(canvas)
    x = pad
    for ch in WORD:
        d.text((x, pad), ch, font=font, fill=255)
        x += int(font.getlength(ch) - OVERLAP * BIG)
    canvas = canvas.crop(canvas.getbbox())
    h = round(canvas.height * WIDTH / canvas.width)
    img = canvas.resize((WIDTH, h), Image.LANCZOS)
    stride = (WIDTH + 1) // 2
    data = bytearray()
    for y in range(h):
        row = [round(img.getpixel((x, y)) * 15 / 255) for x in range(WIDTH)] + [0]
        data += bytes((row[2 * i] << 4) | row[2 * i + 1] for i in range(stride))
    out = Path(__file__).resolve().parent.parent / "firmware" / "gen" / "hera_wordmark.h"
    lines = [f"/* generated by tools/gen_wordmark.py from Playfair Display Black (SIL OFL 1.1): the HERA wordmark, 4-bit coverage */",
             f"#define HERA_WM_W {WIDTH}", f"#define HERA_WM_H {h}", f"#define HERA_WM_STRIDE {stride}",
             "static const unsigned char hera_wordmark[] = {"]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    lines.append("};")
    out.write_text("\n".join(lines) + "\n")
    img.save(out.with_suffix(".png"))
    print(f"{out}: {WIDTH} x {h}, {len(data)} bytes")


if __name__ == "__main__":
    main()
