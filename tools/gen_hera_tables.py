"""Generate firmware/src/hera_tables.h: display names for the Hera UI.

    python3 tools/gen_hera_tables.py            (from the repository root)

Phrase style and variation names come from data/phrase_list.json (the J-6 manual's Phrase List),
shortened to fit the FM-1 screen (8 px characters, 240 px wide).
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "phrase_list.json"
DST = ROOT / "firmware" / "src" / "hera_tables.h"

STYLE_NAMES = {          # short, readable; the manual's category in brackets in the comment
    1: "Arpeggio 8ths",      # ARPEGGIO
    2: "Arpeggio 16ths",     # ARPEGGIO
    3: "Note lengths",       # BEAT
    4: "16th rhythm A",      # BEAT
    5: "16th rhythm B",      # BEAT
    6: "Chords",             # PHRASE: Chord Phrases (Simple)
    7: "Chords rhythmic",    # PHRASE: Chord Phrases (Rhythmic)
    8: "Strum",              # PHRASE: Strummed Chord Phrases (Simple)
    9: "Strum rhythmic",     # PHRASE: Strummed Chord Phrases (Rhythmic)
}


ARP = [("UP&DOWN1", "Up/down"), ("UP&DOWN2", "Up/down 2 oct"), ("DOWN1", "Down"), ("DOWN2", "Down 2 oct"),
       ("UP1", "Up"), ("UP2", "Up 2 oct")]


def short(v):
    for a, b in ARP:
        if v.startswith(a):
            v = b + v[len(a):]
            break
    v = v.replace("(8th Triplet)", "trip").replace("(16th Triplet)", "trip").replace("(8th Tripet)", "trip").replace("(16th Tripet)", "trip")
    v = v.replace("Triplet", "trip").replace("triplet", "trip").replace("Tripet", "trip")
    v = v.replace("Double Whole note", "Double whole").replace("Whole note", "Whole")
    v = v.replace("Half note", "Half").replace("Quarter note", "Quarter").replace("Eighth note", "Eighth")
    v = v.replace("Sixteenth note", "Sixteenth").replace(", Syncopation", " sync")
    v = v.replace(" (8th and 16th)", "").replace(" (16th and 8th)", "").replace(" (dotted 8th and 16th)", "")
    v = v.replace(" (16th)", "").replace(" (8th)", "").replace("(", "").replace(")", "")
    return v.strip()[:18]


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    pl = json.loads(SRC.read_text())
    out = ["/* generated by tools/gen_hera_tables.py from data/phrase_list.json - do not edit */",
           "#ifndef HERA_TABLES_H", "#define HERA_TABLES_H", "",
           "static const char *const HERA_STYLE_NAME[10] = {\"\","]
    out.append("    " + ", ".join(c_str(STYLE_NAMES[s]) for s in range(1, 10)) + "};")
    out.append("")
    out.append("static const char *const HERA_VAR_NAME[10][13] = {")
    out.append("    {\"\"},")
    for s in range(1, 10):
        vs = pl[str(s)]["variations"]
        names = []
        for v in range(1, 13):
            if s <= 5 and str(v) in vs:
                names.append(short(vs[str(v)]))
            else:
                names.append(f"Variation {v}")
        out.append("    {\"\", " + ", ".join(c_str(n) for n in names) + "},")
    out.append("};")
    out += ["", "#endif", ""]
    DST.write_text("\n".join(out))
    print(f"wrote {DST}")


if __name__ == "__main__":
    main()
