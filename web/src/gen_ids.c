/* prints web/hera_ids.js: the engine's parameter / command ids and struct offsets for the editor */
#include <stdio.h>
#include <stddef.h>
#include "j6.h"
#define P(n) printf("  %s: %d,\n", #n, (int)(n))
int main(void)
{
    printf("// generated by web/build.sh from firmware/src/j6/j6.h - do not edit\nexport const ID = {\n");
    P(J6_P_TEMPO10); P(J6_P_LAST); P(J6_P_BEAT); P(J6_P_SHUFFLE); P(J6_P_VOL); P(J6_P_TRAN); P(J6_P_DSYNC);
    P(J6_P_AVEL); P(J6_P_PCHG); P(J6_P_SCLK); P(J6_P_SOUND); P(J6_P_KNOB0); P(J6_P_STYLE_ON); P(J6_P_STYLE);
    P(J6_P_VAR); P(J6_P_CH); P(J6_P_SYNC); P(J6_P_CHORD_SET); P(J6_P_KEY); P(J6_P_OCT); P(J6_P_HOLD);
    P(J6_P_CHORD); P(J6_P_COUNT);
    P(J6_CMD_PLAY); P(J6_CMD_PLAY_FROM); P(J6_CMD_STOP); P(J6_CMD_REC); P(J6_CMD_PATTERN); P(J6_CMD_STEP_SELECT);
    P(J6_CMD_HOLD); P(J6_CMD_STYLE); P(J6_CMD_STEP_CLEAR); P(J6_CMD_PATTERN_CLEAR); P(J6_CMD_PANIC);
    P(J6_SEQ_STOPPED); P(J6_SEQ_PLAYING); P(J6_NO_NOTE); P(J6_NO_CHORD); P(J6_NONE); P(J6_STF_TIE);
    P(J6_STEPS); P(J6_PATTERNS); P(J6_SOUNDS); P(J6_CHORD_SETS);
    printf("  PAT_SIZE: %d, PAT_STEP_OFS: %d, STEP_SIZE: %d,\n", (int)sizeof(j6_pattern_t),
           (int)offsetof(j6_pattern_t, step), (int)sizeof(j6_step_t));
    printf("  PAT_TEMPO: %d, PAT_LAST: %d, PAT_PHRASE: %d, PAT_SOUND: %d,\n", (int)offsetof(j6_pattern_t, tempo10),
           (int)offsetof(j6_pattern_t, last), (int)offsetof(j6_pattern_t, phrase), (int)offsetof(j6_pattern_t, sound));
    printf("  ST_SIZE: %d, ST_SEQ: %d, ST_REC: %d, ST_PATTERN: %d, ST_QUEUED: %d, ST_STEP_NOW: %d, ST_SEL: %d,\n",
           (int)sizeof(j6_status_t), (int)offsetof(j6_status_t, seq_state), (int)offsetof(j6_status_t, recording),
           (int)offsetof(j6_status_t, pattern), (int)offsetof(j6_status_t, queued), (int)offsetof(j6_status_t, step_now),
           (int)offsetof(j6_status_t, sel_step));
    printf("  ST_VOICES: %d, ST_HOLD: %d, ST_CHORD: %d, ST_STYLE_ON: %d, ST_LAST_NOTE: %d, ST_LAST_CHORD: %d,\n",
           (int)offsetof(j6_status_t, voices), (int)offsetof(j6_status_t, hold), (int)offsetof(j6_status_t, chord),
           (int)offsetof(j6_status_t, style_on), (int)offsetof(j6_status_t, last_note), (int)offsetof(j6_status_t, last_chord));
    printf("  ST_TEMPO: %d, ST_DIRTY: %d, ST_KEYS_LIT: %d,\n};\n", (int)offsetof(j6_status_t, tempo10),
           (int)offsetof(j6_status_t, dirty), (int)offsetof(j6_status_t, keys_lit));
    return 0;
}
